#!/usr/bin/env python3
"""
Prepare the self-hosted MiSans (小米兰亭 Pro 体系) subset used by the site.

Why this exists
---------------
The site now uses ONE typeface for both Chinese and Latin, the way Tencent's
own brand typography works (Tencent Sans pairs CJK + Latin from a single
family). Tencent Sans itself is a licensed custom font, so we use MiSans —
the closest freely-licensed humanist CJK/Latin family — and ship a subset
that only contains the characters this page actually renders.

The `misans` npm package publishes variable-weight woff2 chunks keyed by
unicode-range. We pick the chunks that cover (a) printable ASCII, (b) the
punctuation the layout uses, and (c) every CJK character in the copy, then
re-emit a single stylesheet pointing at local files.

Usage:  python3 scripts/prepare-fonts.py
Output: public/fonts/misans/MiSansVF.<hash>.woff2  +  src/styles/misans.css
"""

from __future__ import annotations

import pathlib
import re
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
CSS_SRC = "https://cdn.jsdelivr.net/npm/misans@5.0.0/lib/Normal/MiSansVF.min.css"
CDN = "https://cdn.jsdelivr.net/npm/misans@5.0.0/lib/Normal/"
OUT_FONTS = ROOT / "public" / "fonts" / "misans"
OUT_CSS = ROOT / "src" / "styles" / "misans.css"

# characters the layout leans on even when the copy does not contain them
EXTRA = set(
    "".join(chr(c) for c in range(0x20, 0x7F))
    + "·—–×°‘’“”…→←↑↓≈≤≥✓•§©®™"
)


def fetch(url: str) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": "curl/8"})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read()


def wanted_codepoints() -> set[int]:
    cps = {ord(c) for c in EXTRA}
    for path in list((ROOT / "src").rglob("*.ts")) + list((ROOT / "src").rglob("*.tsx")):
        if path.name == "misans.css":
            continue
        for ch in path.read_text(encoding="utf-8"):
            cps.add(ord(ch))
    html = (ROOT / "index.html").read_text(encoding="utf-8")
    cps.update(ord(ch) for ch in html)
    # never subset away characters we cannot see in the source (control chars)
    return {c for c in cps if c >= 0x20}


def parse_range(text: str) -> set[int]:
    out: set[int] = set()
    for part in text.split(","):
        part = part.strip().upper().replace("U+", "")
        if not part:
            continue
        if "-" in part:
            a, b = part.split("-")
            out.update(range(int(a, 16), int(b, 16) + 1))
        else:
            out.add(int(part, 16))
    return out


def main() -> None:
    css_text = fetch(CSS_SRC).decode("utf-8")
    blocks = re.findall(r"@font-face\{([^}]*)\}", css_text)
    if not blocks:
        raise SystemExit("no @font-face blocks found in the MiSans stylesheet")

    need = wanted_codepoints()
    chosen: list[tuple[str, str, set[int]]] = []
    for block in blocks:
        url = re.search(r"url\('([^']+)'\)", block).group(1)
        rng = re.search(r"unicode-range:\s*([^;}]+)", block)
        covered = parse_range(rng.group(1)) if rng else set()
        if covered & need:
            chosen.append((url, rng.group(1) if rng else "", covered))

    OUT_FONTS.mkdir(parents=True, exist_ok=True)
    total = 0
    faces: list[str] = []
    for url, rng, covered in chosen:
        target = OUT_FONTS / url
        if not target.exists():
            data = fetch(CDN + url)
            target.write_bytes(data)
        total += target.stat().st_size
        faces.append(
            "@font-face{font-family:'MiSans';font-style:normal;font-weight:150 700;"
            f"font-display:swap;src:url('/fonts/misans/{url}') format('woff2');"
            + (f"unicode-range:{rng};" if rng else "")
            + "}"
        )

    OUT_CSS.parent.mkdir(parents=True, exist_ok=True)
    OUT_CSS.write_text(
        "/* generated by scripts/prepare-fonts.py — do not edit by hand */\n"
        + "\n".join(sorted(faces))
        + "\n",
        encoding="utf-8",
    )

    covered_need = set().union(*[c for _, _, c in chosen]) if chosen else set()
    missing = sorted(need - covered_need)
    print(f"blocks used: {len(chosen)}  bytes: {total/1024:.1f} KB")
    print(f"chars wanted: {len(need)}  uncovered: {len(missing)}")
    if missing:
        print("  missing:", "".join(chr(c) for c in missing[:60]))


if __name__ == "__main__":
    main()
